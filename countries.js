// Party datasets per country. Each party row is [abbr, name, colour, [x, y, z, w], seats]:
//   x economic        -1 state redistribution ... +1 free market
//   y sociocultural   -1 TAN ... +1 GAL
//   z institutional   -1 institutionalist/technocratic ... +1 anti-establishment/populist
//   w tempo           -1 incrementalist ... +1 radical
// The [x, y, z, w] vectors are rough, illustrative estimates, NOT survey measurements: X and Y loosely follow
// Chapel Hill Expert Survey dimensions (galtan inverted); Z and W are subjective.
//
// `seats` = mandates won in the country's latest national election of the main (lower) chamber, as of Nov 2026,
// taken from national election bodies / Wikipedia / news reports. 0 = contested or exists but holds no seats.
// Parties that won only a handful of seats are not all listed, so listed seats can sum to less than `total`.
// `approx` ('group' | 'composition' | 'notfinal') marks countries where seat figures are approximate.
// `election` = { chamber, date: 'YYYY-MM', total, approx? }; the display text is built in i18n.js (electionLabel).

const country = (code, name, group, election, rows) => ({
  code,
  name,
  group,
  election,
  parties: rows.map(([abbr, pname, color, vec, seats]) => ({
    id: `${code}:${abbr}`, country: code, abbr, name: pname, partyColor: color, vec, seats, total: election.total,
  })),
});

